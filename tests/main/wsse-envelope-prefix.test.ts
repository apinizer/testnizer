/**
 * WS-Security on envelopes that do not use the `soap:` prefix
 * (tester report 2026-10-30).
 *
 * The engine located Header / Body with hard-coded `soap:` regexes and wrote
 * `soap:mustUnderstand`. A SoapUI envelope (`soapenv:`), any other prefix or a
 * default-namespace envelope came back UNCHANGED and the call "succeeded"; and
 * had the header been inserted, `soap:mustUnderstand` would have been an
 * unbound prefix (malformed XML).
 *
 * Every output here is parsed with a namespace-aware parser whose errors are
 * fatal, and its STRUCTURE is checked: Security sits in the Header that is the
 * first element child of the Envelope, in the envelope's namespace, and
 * carries the envelope-namespace `mustUnderstand`.
 */
import { describe, it, expect, beforeAll } from 'vitest'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { DOMParser, type Document, type Element } from '@xmldom/xmldom'
import {
  applyWsSecurity,
  verifySignature,
  decryptEnvelope,
  WSSE_NS,
  type WsSecurityConfig,
} from '../../src/main/protocols/wsse.engine'

const SOAP11 = 'http://schemas.xmlsoap.org/soap/envelope/'
const SOAP12 = 'http://www.w3.org/2003/05/soap-envelope'
const CERTS = path.resolve(__dirname, '../fixtures/certs')

let certPem: string
let keyPem: string

beforeAll(() => {
  certPem = readFileSync(path.join(CERTS, 'server.crt'), 'utf8')
  keyPem = readFileSync(path.join(CERTS, 'server.key'), 'utf8')
})

/** Parse with every warning / error fatal — malformed output fails the test. */
function parseStrict(xml: string): Document {
  const parser = new DOMParser({
    onError: (level: string, msg: string) => {
      throw new Error(`XML ${level}: ${msg}`)
    },
  })
  return parser.parseFromString(xml, 'text/xml') as unknown as Document
}

function elementChildren(el: Element): Element[] {
  const out: Element[] = []
  for (let n = el.firstChild; n; n = n.nextSibling) {
    if (n.nodeType === 1) out.push(n as Element)
  }
  return out
}

/** The structural contract every WSSE output must meet. */
function assertSecurityHeader(xml: string, envNs: string): Document {
  const doc = parseStrict(xml)
  const env = doc.documentElement as Element
  expect(env.localName).toBe('Envelope')
  expect(env.namespaceURI).toBe(envNs)
  const children = elementChildren(env)
  const header = children[0]
  expect(header.localName).toBe('Header')
  expect(header.namespaceURI).toBe(envNs)
  expect(children.filter((c) => c.localName === 'Header')).toHaveLength(1)
  const security = elementChildren(header).find(
    (c) => c.localName === 'Security' && c.namespaceURI === WSSE_NS,
  )
  expect(security).toBeDefined()
  expect(security!.getAttributeNS(envNs, 'mustUnderstand')).toBe('1')
  const body = children.find((c) => c.localName === 'Body')
  expect(body?.namespaceURI).toBe(envNs)
  return doc
}

const SOAPUI_ENVELOPE = `<soapenv:Envelope xmlns:soapenv="${SOAP11}" xmlns:tem="http://tempuri.org/">
   <soapenv:Header/>
   <soapenv:Body>
      <tem:Add>
         <tem:intA>1</tem:intA>
         <tem:intB>2</tem:intB>
      </tem:Add>
   </soapenv:Body>
</soapenv:Envelope>`

const DEFAULT_NS_ENVELOPE = `<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by a client that uses a default namespace -->
<Envelope xmlns="${SOAP11}">
  <Body>
    <Add xmlns="http://tempuri.org/"><intA>1</intA><intB>2</intB></Add>
  </Body>
</Envelope>`

const SOAP12_ENVELOPE = `<env:Envelope xmlns:env="${SOAP12}"><env:Header></env:Header><env:Body><m:Ping xmlns:m="urn:ping"/></env:Body></env:Envelope>`

const UT: WsSecurityConfig = {
  enabled: true,
  modes: ['username-token'],
  usernameToken: {
    username: 'alice',
    password: 'pw-123456',
    passwordType: 'PasswordText',
    nonce: true,
    created: true,
  },
}
const TS: WsSecurityConfig = { enabled: true, modes: ['timestamp'], timestamp: { ttlSeconds: 60 } }

function signConfig(): WsSecurityConfig {
  return {
    enabled: true,
    modes: ['sign'],
    sign: {
      privateKeyPem: keyPem,
      certPem,
      algorithm: 'RSA-SHA256',
      references: ['Body'],
      keyInfoStrategy: 'BinarySecurityToken',
    },
  }
}

function encryptConfig(): WsSecurityConfig {
  return {
    enabled: true,
    modes: ['encrypt'],
    encrypt: { recipientCertPem: certPem, algorithm: 'AES-256-CBC', keyWrap: 'RSA-OAEP' },
  }
}

describe('SoapUI `soapenv:` envelope', () => {
  it('UsernameToken is inserted into the existing self-closing Header', async () => {
    const out = await applyWsSecurity(SOAPUI_ENVELOPE, UT)
    expect(out).not.toBe(SOAPUI_ENVELOPE)
    expect(out).not.toContain('soap:mustUnderstand')
    expect(out).toContain('soapenv:mustUnderstand="1"')
    expect(out).toContain('<wsse:Username>alice</wsse:Username>')
    assertSecurityHeader(out, SOAP11)
  })

  it('Timestamp is inserted', async () => {
    const out = await applyWsSecurity(SOAPUI_ENVELOPE, TS)
    expect(out).toContain('<wsu:Timestamp')
    assertSecurityHeader(out, SOAP11)
  })

  it('Sign: the Body is signed and the signature verifies', async () => {
    const out = await applyWsSecurity(SOAPUI_ENVELOPE, signConfig())
    const doc = assertSecurityHeader(out, SOAP11)
    const body = elementChildren(doc.documentElement as Element).find((c) => c.localName === 'Body')
    expect(body?.getAttribute('wsu:Id')).toMatch(/^Body-/)
    const v = verifySignature(out, certPem)
    expect(v.valid).toBe(true)
  })

  it('Encrypt: the Body content becomes EncryptedData and decrypts back', async () => {
    const out = await applyWsSecurity(SOAPUI_ENVELOPE, encryptConfig())
    assertSecurityHeader(out, SOAP11)
    expect(out).toContain('EncryptedData')
    expect(out).not.toContain('<tem:intA>')
    const plain = await decryptEnvelope(out, keyPem)
    expect(plain).toContain('<tem:intA>1</tem:intA>')
    parseStrict(plain)
  })

  it('UsernameToken + Timestamp + Sign + Encrypt together stay well-formed', async () => {
    const out = await applyWsSecurity(SOAPUI_ENVELOPE, {
      enabled: true,
      modes: ['username-token', 'timestamp', 'sign', 'encrypt'],
      usernameToken: UT.usernameToken,
      timestamp: TS.timestamp,
      sign: { ...signConfig().sign!, references: ['Body', 'Timestamp'] },
      encrypt: encryptConfig().encrypt,
    })
    assertSecurityHeader(out, SOAP11)
  })
})

describe('default-namespace envelope (no prefix)', () => {
  it('creates the Header as the first child and declares a prefix for mustUnderstand', async () => {
    const out = await applyWsSecurity(DEFAULT_NS_ENVELOPE, UT)
    expect(out).not.toBe(DEFAULT_NS_ENVELOPE)
    assertSecurityHeader(out, SOAP11)
  })

  it('a payload element called Header is not mistaken for the SOAP Header', async () => {
    const env = `<Envelope xmlns="${SOAP11}"><Body><Header>payload</Header></Body></Envelope>`
    const out = await applyWsSecurity(env, TS)
    const doc = assertSecurityHeader(out, SOAP11)
    const body = elementChildren(doc.documentElement as Element).find((c) => c.localName === 'Body')!
    const inner = elementChildren(body)[0]
    expect(inner.localName).toBe('Header')
    expect(inner.textContent).toBe('payload')
    expect(elementChildren(inner)).toHaveLength(0)
  })

  it('Sign and Encrypt find the unprefixed Body', async () => {
    const signed = await applyWsSecurity(DEFAULT_NS_ENVELOPE, signConfig())
    assertSecurityHeader(signed, SOAP11)
    expect(verifySignature(signed, certPem).valid).toBe(true)
    const enc = await applyWsSecurity(DEFAULT_NS_ENVELOPE, encryptConfig())
    assertSecurityHeader(enc, SOAP11)
    expect(enc).toContain('EncryptedData')
    expect(enc).not.toContain('<intA>')
  })
})

describe('SOAP 1.2 envelope', () => {
  it('uses the 1.2 namespace and the envelope prefix', async () => {
    const out = await applyWsSecurity(SOAP12_ENVELOPE, UT)
    expect(out).toContain('env:mustUnderstand="1"')
    assertSecurityHeader(out, SOAP12)
  })

  it('signs a 1.2 Body', async () => {
    const out = await applyWsSecurity(SOAP12_ENVELOPE, signConfig())
    assertSecurityHeader(out, SOAP12)
    expect(verifySignature(out, certPem).valid).toBe(true)
  })
})

describe('Header placement', () => {
  it('keeps the content of an existing Header (with attributes)', async () => {
    const env = `<s:Envelope xmlns:s="${SOAP11}"><s:Header xmlns:a="urn:a"><a:Trace>t-1</a:Trace></s:Header><s:Body><x/></s:Body></s:Envelope>`
    const out = await applyWsSecurity(env, UT)
    const doc = assertSecurityHeader(out, SOAP11)
    const header = elementChildren(doc.documentElement as Element)[0]
    expect(elementChildren(header).map((c) => c.localName)).toEqual(['Security', 'Trace'])
  })

  it('creates the Header when there is none', async () => {
    const env = `<s:Envelope xmlns:s="${SOAP11}"><s:Body><x/></s:Body></s:Envelope>`
    const out = await applyWsSecurity(env, TS)
    assertSecurityHeader(out, SOAP11)
  })

  it('a self-closing Header with attributes is opened', async () => {
    const env = `<s:Envelope xmlns:s="${SOAP11}"><s:Header a="1" /><s:Body><x/></s:Body></s:Envelope>`
    const out = await applyWsSecurity(env, TS)
    assertSecurityHeader(out, SOAP11)
  })

  it('an existing wsu:Id on the Body is reused, not duplicated', async () => {
    const WSU =
      'http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-utility-1.0.xsd'
    const env = `<s:Envelope xmlns:s="${SOAP11}"><s:Body xmlns:wsu="${WSU}" wsu:Id="b1"><x/></s:Body></s:Envelope>`
    const out = await applyWsSecurity(env, signConfig())
    const doc = assertSecurityHeader(out, SOAP11)
    const body = elementChildren(doc.documentElement as Element).find((c) => c.localName === 'Body')!
    expect(body.getAttributeNS(WSU, 'Id')).toBe('b1')
    expect(verifySignature(out, certPem).valid).toBe(true)
  })
})

describe('input that is not a SOAP envelope is an error, never returned unchanged', () => {
  it.each([
    ['a plain XML document', '<Order><id>1</id></Order>'],
    ['JSON text', '{"a":1}'],
    ['an Envelope in a foreign namespace', '<e:Envelope xmlns:e="urn:not-soap"><e:Body/></e:Envelope>'],
    ['an Envelope with an unbound prefix', '<soapenv:Envelope><soapenv:Body/></soapenv:Envelope>'],
    ['an empty string', ''],
  ])('%s', async (_label, input) => {
    await expect(applyWsSecurity(input, UT)).rejects.toThrow(/SOAP Envelope/i)
  })

  it('a disabled config still passes any body through untouched', async () => {
    expect(await applyWsSecurity('{"a":1}', { enabled: false, modes: [] })).toBe('{"a":1}')
  })
})
